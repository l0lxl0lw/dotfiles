#!/usr/bin/env python3
"""Render the canonical workflow agents into each host's native agent format.

Sources: ai/shared/agents/<name>.md (name, description, tier, access, delegates).
Model names live only in tiers.json; an unmapped tier or `inherit` uses the
session model. Outputs are committed so every sync stays a plain symlink:

    ai/claude/agents/workflow/<name>.md
    ai/codex/agents/<name>.toml

Run without arguments to write, or with --check to fail on drift.
"""
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
AI = HERE.parent.parent
TIERS = ('fast', 'standard', 'strong', 'inherit')
NOTICE = 'Generated by ai/shared/agents/render.py from ai/shared/agents/{}.md; edit the source instead.'

# Claude subagents cannot spawn subagents, and its search runs through Bash on
# some builds, so profiles deny writers rather than allow-listing tool names.
CLAUDE_DISALLOWED = {
    'research': 'Edit, Write, NotebookEdit',
    'draft': 'Edit, Write, NotebookEdit, AskUserQuestion',
    'review': 'Edit, Write, NotebookEdit',
    'write': '',
}
# Read-only roles are sandboxed; review/write inherit the parent's sandbox so
# verification can write its private logs under the state directory.
CODEX_SANDBOX = {'research': 'read-only', 'draft': 'read-only', 'review': '', 'write': ''}


def parse(path):
    _, front, body = path.read_text().split('---', 2)
    meta = {}
    for line in front.strip().splitlines():
        key, _, value = line.partition(':')
        meta[key.strip()] = value.strip()
    if meta.get('name') != path.stem:
        raise SystemExit(f'{path}: name must match the file name')
    if meta.get('tier') not in TIERS:
        raise SystemExit(f'{path}: tier must be one of {", ".join(TIERS)}')
    if meta.get('access') not in CLAUDE_DISALLOWED:
        raise SystemExit(f'{path}: access must be one of {", ".join(CLAUDE_DISALLOWED)}')
    if not meta.get('description'):
        raise SystemExit(f'{path}: description is required')
    meta['delegates'] = [d.strip() for d in meta.get('delegates', '').split(',') if d.strip()]
    if meta['delegates'] and meta['access'] != 'write':
        raise SystemExit(f'{path}: only write agents may delegate')
    meta['body'] = body.lstrip('\n')
    return meta


def tier(tiers, host, meta):
    return tiers.get(host, {}).get(meta['tier'], {}) if meta['tier'] != 'inherit' else {}


def claude(meta, tiers):
    model = tier(tiers, 'claude', meta)
    lines = ['---', '# ' + NOTICE.format(meta['name']), 'name: ' + meta['name'],
             'description: ' + meta['description']]
    if model.get('model'):
        lines.append('model: ' + model['model'])
    if model.get('effort'):
        lines.append('effort: ' + model['effort'])
    if CLAUDE_DISALLOWED[meta['access']]:
        lines.append('disallowedTools: ' + CLAUDE_DISALLOWED[meta['access']])
    return '\n'.join(lines + ['---', '', meta['body']])


def codex(meta, tiers):
    model = tier(tiers, 'codex', meta)
    if "'''" in meta['body']:
        raise SystemExit(f"{meta['name']}: body cannot contain ''' (TOML literal string delimiter)")
    lines = ['# ' + NOTICE.format(meta['name']), 'name = ' + json.dumps(meta['name']),
             'description = ' + json.dumps(meta['description'])]
    if model.get('model'):
        lines.append('model = ' + json.dumps(model['model']))
    if model.get('effort'):
        lines.append('model_reasoning_effort = ' + json.dumps(model['effort']))
    if CODEX_SANDBOX[meta['access']]:
        lines.append('sandbox_mode = ' + json.dumps(CODEX_SANDBOX[meta['access']]))
    lines.append("developer_instructions = '''\n" + meta['body'] + "'''")
    return '\n'.join(lines) + '\n'


def outputs(root=AI):
    tiers = json.loads((HERE / 'tiers.json').read_text())
    unknown = {t for host in tiers.values() for t in host} - set(TIERS[:-1])
    if unknown:
        raise SystemExit('tiers.json: unknown or reserved tiers: ' + ', '.join(sorted(unknown)))
    result = {}
    for path in sorted(HERE.glob('*.md')):
        if path.name == 'README.md':
            continue
        meta = parse(path)
        result[root / 'claude/agents/workflow' / (meta['name'] + '.md')] = claude(meta, tiers)
        result[root / 'codex/agents' / (meta['name'] + '.toml')] = codex(meta, tiers)
    return result


def stale(root=AI):
    """Generated paths whose content differs, plus orphans in the generated directories."""
    wanted = outputs(root)
    drift = [p for p, text in wanted.items() if not p.is_file() or p.read_text() != text]
    for directory, pattern in ((root / 'claude/agents/workflow', '*.md'), (root / 'codex/agents', '*.toml')):
        drift += [p for p in directory.glob(pattern) if p not in wanted]
    return wanted, sorted(drift)


def main(argv):
    wanted, drift = stale()
    if argv[1:] == ['--check']:
        for path in drift:
            print('stale: ' + str(path.relative_to(AI)), file=sys.stderr)
        return 1 if drift else 0
    if argv[1:]:
        print('usage: render.py [--check]', file=sys.stderr)
        return 2
    for path in drift:
        if path in wanted:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted[path])
        else:
            path.unlink()
        print('wrote ' if path in wanted else 'removed ', path.relative_to(AI), sep='')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
