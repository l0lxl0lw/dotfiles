"""agents/render.py renders a hub's agents/src into Claude, Codex and OpenCode files."""
import importlib.util
import json
from pathlib import Path
import tempfile
import tomllib
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("hub_render", ROOT / "agents/render.py")
render = importlib.util.module_from_spec(spec)
spec.loader.exec_module(render)

TIERS = {
    "claude": {"fast": {"model": "haiku"}, "standard": {"model": "sonnet"}},
    "codex": {"fast": {"model": "gpt-6-luna", "effort": "medium"}},
    "opencode": {"fast": {"model": "openai/gpt-6-luna"}},
}
LOCATOR = "---\nname: locator\ndescription: Find things.\ntier: fast\naccess: research\n---\n\nLocate the code.\n"
EXECUTOR = "---\nname: executor\ndescription: Do things.\ntier: inherit\naccess: write\n---\n\nImplement the plan.\n"


def frontmatter(text):
    return dict(line.split(": ", 1) for line in text.split("---")[1].strip().splitlines()
                if not line.startswith("#") and ": " in line)


def make_hub(root):
    src = root / "agents/src"
    src.mkdir(parents=True)
    (src / "locator.md").write_text(LOCATOR)
    (src / "executor.md").write_text(EXECUTOR)
    (root / "tiers.json").write_text(json.dumps(TIERS))
    return root


class HubRenderTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.hub = make_hub(Path(self.tmp.name) / "hub")

    def tearDown(self):
        self.tmp.cleanup()

    def test_writes_three_hosts_per_source(self):
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub)]), 0)
        for name in ("locator", "executor"):
            self.assertTrue((self.hub / f".claude/agents/{name}.md").is_file(), name)
            self.assertTrue((self.hub / f".codex/agents/{name}.toml").is_file(), name)
            self.assertTrue((self.hub / f".opencode/agents/{name}.md").is_file(), name)
        claude = (self.hub / ".claude/agents/locator.md").read_text()
        self.assertTrue(claude.endswith("Locate the code.\n"))
        self.assertEqual(frontmatter(claude)["model"], "haiku")
        self.assertEqual(frontmatter(claude)["disallowedTools"], "Edit, Write, NotebookEdit")
        codex = tomllib.loads((self.hub / ".codex/agents/locator.toml").read_text())
        self.assertEqual((codex["model"], codex["sandbox_mode"]), ("gpt-6-luna", "read-only"))
        first = (self.hub / ".codex/agents/locator.toml").read_text().splitlines()[0]
        self.assertTrue(first.startswith("# Generated by render.py from "), first)
        self.assertIn("agents/src/locator.md", first)

    def test_opencode_frontmatter(self):
        render.main(["render.py", "--hub", str(self.hub)])
        locator = (self.hub / ".opencode/agents/locator.md").read_text()
        fm = frontmatter(locator)
        self.assertEqual(fm["mode"], "subagent")
        self.assertEqual(fm["description"], "Find things.")
        self.assertEqual(fm["model"], "openai/gpt-6-luna")
        self.assertIn("permissions:", locator)
        self.assertIn("effect: deny", locator)
        self.assertIn("action: edit", locator)
        self.assertTrue(locator.endswith("Locate the code.\n"))
        executor = (self.hub / ".opencode/agents/executor.md").read_text()
        self.assertNotIn("model:", executor.split("---")[1])
        self.assertNotIn("permissions:", executor)

    def test_overlay_tiers_last_wins(self):
        a = Path(self.tmp.name) / "a.json"
        b = Path(self.tmp.name) / "b.json"
        a.write_text(json.dumps({"opencode": {"fast": {"model": "openrouter/a"}}}))
        b.write_text(json.dumps({"opencode": {"fast": {"model": "openrouter/b"}}}))
        tiers = render.load_tiers(self.hub, [a, b])
        self.assertEqual(tiers["opencode"]["fast"]["model"], "openrouter/b")
        self.assertEqual(tiers["claude"]["fast"]["model"], "haiku")

    def test_check_reports_drift_and_orphans(self):
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub), "--check"]), 1)
        render.main(["render.py", "--hub", str(self.hub)])
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub), "--check"]), 0)
        (self.hub / ".codex/agents/orphan.toml").write_text(
            "# Generated by render.py from agents/src/orphan.md; edit the source instead.\nname = \"orphan\"\n")
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub), "--check"]), 1)
        render.main(["render.py", "--hub", str(self.hub)])
        self.assertFalse((self.hub / ".codex/agents/orphan.toml").exists())

    def test_check_reports_markdown_orphans(self):
        render.main(["render.py", "--hub", str(self.hub)])
        orphan = self.hub / ".claude/agents/old.md"
        orphan.write_text("---\n# Generated by render.py from agents/src/old.md; edit the source instead.\nname: old\n---\n\nx\n")
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub), "--check"]), 1)
        render.main(["render.py", "--hub", str(self.hub)])
        self.assertFalse(orphan.exists())

    def test_claude_only_agent_untouched(self):
        hand = self.hub / ".claude/agents/azubot.md"
        hand.parent.mkdir(parents=True)
        hand.write_text("---\nname: azubot\ndescription: persona\n---\n\nhand written\n")
        render.main(["render.py", "--hub", str(self.hub)])
        self.assertEqual(render.main(["render.py", "--hub", str(self.hub), "--check"]), 0)
        self.assertEqual(hand.read_text(), "---\nname: azubot\ndescription: persona\n---\n\nhand written\n")

    def test_out_dirs_write_only_those_hosts(self):
        codex_out = Path(self.tmp.name) / "codex"
        opencode_out = Path(self.tmp.name) / "opencode"
        overlay = Path(self.tmp.name) / "machine.json"
        overlay.write_text(json.dumps({"opencode": {"fast": {"model": "openrouter/m"}}}))
        rc = render.main(["render.py", "--hub", str(self.hub), "--tiers", str(overlay),
                          "--codex-out", str(codex_out), "--opencode-out", str(opencode_out)])
        self.assertEqual(rc, 0)
        self.assertTrue((codex_out / "locator.toml").is_file())
        self.assertEqual(frontmatter((opencode_out / "locator.md").read_text())["model"], "openrouter/m")
        self.assertFalse((self.hub / ".claude").exists())
        self.assertFalse((self.hub / ".opencode").exists())


if __name__ == "__main__":
    unittest.main()
