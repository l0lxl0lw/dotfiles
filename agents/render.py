#!/usr/bin/env python3
"""Render a hub's workflow agents into each host's native agent format.

Sources: <hub>/agents/src/<name>.md with frontmatter name, description, tier,
access and delegates. Model names live only in tiers files; an unmapped tier or
`inherit` uses the session model. Committed outputs, so a hub works when a
session starts inside it with no linker:

    <hub>/.claude/agents/<name>.md
    <hub>/.codex/agents/<name>.toml
    <hub>/.opencode/agents/<name>.md

    render.py --hub PATH [--tiers FILE ...] [--check]
    render.py --hub PATH [--tiers FILE ...] --codex-out DIR --opencode-out DIR

--tiers files overlay <hub>/tiers.json host by host, last wins; the linker
passes the machine-local one. With out dirs only those hosts are written,
there, with the merged tiers (the per-machine render). --check exits 1 on
drift. Agent files under .claude/agents with no agents/src entry are
Claude-only and left alone.
"""
import json
from pathlib import Path
import sys

TIERS = ('fast', 'standard', 'strong', 'inherit')
HOSTS = ('claude', 'codex', 'opencode', 'orca')
NOTICE = 'Generated by render.py from agents/src/{}.md; edit the source instead.'

# Claude subagents cannot spawn subagents, and its search runs through Bash on
# some builds, so profiles deny writers rather than allow-listing tool names.
CLAUDE_DISALLOWED = {
    'research': 'Edit, Write, NotebookEdit',
    'draft': 'Edit, Write, NotebookEdit, AskUserQuestion',
    'review': 'Edit, Write, NotebookEdit',
    'write': '',
}
# Read-only roles are sandboxed; review/write inherit the parent's sandbox so
# verification can write its private logs under the state directory.
CODEX_SANDBOX = {'research': 'read-only', 'draft': 'read-only', 'review': '', 'write': ''}
# OpenCode permission rules per access, as `action` values from
# opencode.ai/docs/agents (V2): `edit` covers edit, write and patch. There is
# no documented action for asking the user, so draft equals research here.
OPENCODE_DENY = {
    'research': ('edit',),
    'draft': ('edit',),
    'review': ('edit',),
    'write': (),
}


def parse(path):
    _, front, body = path.read_text().split('---', 2)
    meta = {}
    for line in front.strip().splitlines():
        key, _, value = line.partition(':')
        meta[key.strip()] = value.strip()
    if meta.get('name') != path.stem:
        raise SystemExit(f'{path}: name must match the file name')
    if meta.get('tier') not in TIERS:
        raise SystemExit(f'{path}: tier must be one of {", ".join(TIERS)}')
    if meta.get('access') not in CLAUDE_DISALLOWED:
        raise SystemExit(f'{path}: access must be one of {", ".join(CLAUDE_DISALLOWED)}')
    if not meta.get('description'):
        raise SystemExit(f'{path}: description is required')
    meta['delegates'] = [d.strip() for d in meta.get('delegates', '').split(',') if d.strip()]
    if meta['delegates'] and meta['access'] != 'write':
        raise SystemExit(f'{path}: only write agents may delegate')
    meta['body'] = body.lstrip('\n')
    return meta


def load_tiers(hub, overlays=()):
    """<hub>/tiers.json with each overlay file applied host by host, last wins."""
    merged = {}
    files = [hub / 'tiers.json'] + [Path(p) for p in overlays]
    for path in files:
        if not path.is_file():
            continue
        data = json.loads(path.read_text())
        unknown = set(data) - set(HOSTS)
        if unknown:
            raise SystemExit(f'{path}: unknown hosts: {", ".join(sorted(unknown))}')
        for host, tiers in data.items():
            bad = set(tiers) - set(TIERS[:-1])
            if bad:
                raise SystemExit(f'{path}: unknown or reserved tiers: {", ".join(sorted(bad))}')
            merged.setdefault(host, {}).update(tiers)
    return merged


def tier(tiers, host, meta):
    return tiers.get(host, {}).get(meta['tier'], {}) if meta['tier'] != 'inherit' else {}


def claude(meta, tiers):
    model = tier(tiers, 'claude', meta)
    lines = ['---', '# ' + NOTICE.format(meta['name']), 'name: ' + meta['name'],
             'description: ' + meta['description']]
    if model.get('model'):
        lines.append('model: ' + model['model'])
    if model.get('effort'):
        lines.append('effort: ' + model['effort'])
    if CLAUDE_DISALLOWED[meta['access']]:
        lines.append('disallowedTools: ' + CLAUDE_DISALLOWED[meta['access']])
    return '\n'.join(lines + ['---', '', meta['body']])


def codex(meta, tiers):
    model = tier(tiers, 'codex', meta)
    if "'''" in meta['body']:
        raise SystemExit(f"{meta['name']}: body cannot contain ''' (TOML literal string delimiter)")
    lines = ['# ' + NOTICE.format(meta['name']), 'name = ' + json.dumps(meta['name']),
             'description = ' + json.dumps(meta['description'])]
    if model.get('model'):
        lines.append('model = ' + json.dumps(model['model']))
    if model.get('effort'):
        lines.append('model_reasoning_effort = ' + json.dumps(model['effort']))
    if CODEX_SANDBOX[meta['access']]:
        lines.append('sandbox_mode = ' + json.dumps(CODEX_SANDBOX[meta['access']]))
    lines.append("developer_instructions = '''\n" + meta['body'] + "'''")
    return '\n'.join(lines) + '\n'


def opencode(meta, tiers):
    model = tier(tiers, 'opencode', meta)
    lines = ['---', '# ' + NOTICE.format(meta['name']), 'description: ' + meta['description'],
             'mode: subagent']
    if model.get('model'):
        lines.append('model: ' + model['model'] + ('#' + model['effort'] if model.get('effort') else ''))
    if OPENCODE_DENY[meta['access']]:
        lines.append('permissions:')
        for action in OPENCODE_DENY[meta['access']]:
            lines += [f'  - action: {action}', '    resource: "*"', '    effect: deny']
    return '\n'.join(lines + ['---', '', meta['body']])


HOST_OUT = {
    'claude': ('.claude/agents', '.md', claude),
    'codex': ('.codex/agents', '.toml', codex),
    'opencode': ('.opencode/agents', '.md', opencode),
}


def outputs(hub, tiers, codex_out=None, opencode_out=None):
    """Wanted path -> text. With out dirs, only Codex/OpenCode, written there."""
    dirs = {host: hub / sub for host, (sub, _, _) in HOST_OUT.items()}
    if codex_out or opencode_out:
        dirs = {}
        if codex_out:
            dirs['codex'] = Path(codex_out)
        if opencode_out:
            dirs['opencode'] = Path(opencode_out)
    result = {}
    for path in sorted((hub / 'agents/src').glob('*.md')):
        meta = parse(path)
        for host, out in dirs.items():
            _, ext, fn = HOST_OUT[host]
            result[out / (meta['name'] + ext)] = fn(meta, tiers)
    return result, dirs


def generated(path):
    try:
        first = path.read_text().splitlines()[0]
    except (OSError, IndexError, UnicodeDecodeError):
        return False
    return first.lstrip('# ').startswith('Generated by render.py')


def stale(hub, tiers, codex_out=None, opencode_out=None):
    """Paths whose content differs, plus generated orphans in the output directories."""
    wanted, dirs = outputs(hub, tiers, codex_out, opencode_out)
    drift = [p for p, text in wanted.items() if not p.is_file() or p.read_text() != text]
    for host, out in dirs.items():
        ext = HOST_OUT[host][1]
        drift += [p for p in out.glob('*' + ext) if p not in wanted and generated(p)]
    return wanted, sorted(drift)


def main(argv):
    args = list(argv[1:])
    hub = None
    overlays, check, codex_out, opencode_out = [], False, None, None
    while args:
        flag = args.pop(0)
        if flag == '--hub':
            hub = Path(args.pop(0)).resolve()
        elif flag == '--tiers':
            overlays.append(args.pop(0))
        elif flag == '--codex-out':
            codex_out = args.pop(0)
        elif flag == '--opencode-out':
            opencode_out = args.pop(0)
        elif flag == '--check':
            check = True
        else:
            print('usage: render.py --hub PATH [--tiers FILE]... [--check] '
                  '[--codex-out DIR] [--opencode-out DIR]', file=sys.stderr)
            return 2
    if hub is None or not (hub / 'agents/src').is_dir():
        print('render.py: --hub must name a directory with agents/src', file=sys.stderr)
        return 2
    tiers = load_tiers(hub, overlays)
    wanted, drift = stale(hub, tiers, codex_out, opencode_out)
    if check:
        for path in drift:
            print('stale: ' + str(path), file=sys.stderr)
        return 1 if drift else 0
    for path in drift:
        if path in wanted:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted[path])
        else:
            path.unlink()
        print(('wrote ' if path in wanted else 'removed ') + str(path))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
